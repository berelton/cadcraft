/// Decode one stroke string into point lists in font units.
pub(crate) fn strokes(spec: &str) -> Vec<Vec<(f64, f64)>> {
    spec.split(' ')
        .filter(|s| !s.is_empty())
        .map(|s| {
            let b = s.as_bytes();
            b.chunks(2)
                .filter_map(|p| {
                    let x = f64::from(p.first()?.checked_sub(b'0')?);
                    let y = f64::from(p.get(1)?.checked_sub(b'a')?) - 2.0;
                    Some((x, y))
                })
                .collect()
        })
        .collect()
}
